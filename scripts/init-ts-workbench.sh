#!/usr/bin/env bash
# ============================================================================
# init-ts-workbench.sh — 生成故障排查工作台骨架（本机/远程/环境分层）
# 用法: scripts/init-ts-workbench.sh <目标目录>
# 生成: sop/{通用故障模式,本机经验,环境基线}/ + incidents/ + reports/ + AGENTS.md
# 自包含：任何 Agent 打开即用。
# ============================================================================
set -euo pipefail
TARGET="${1:-}"; [ -n "$TARGET" ] || { echo "用法: scripts/init-ts-workbench.sh <目标目录>" >&2; exit 1; }
[ -d "$TARGET" ] && [ -n "$(ls -A "$TARGET")" ] && { echo "错误: 目标目录非空" >&2; exit 1; }
mkdir -p "$TARGET"/{sop/{通用故障模式,本机经验,环境基线},incidents,reports}

cat > "$TARGET/AGENTS.md" <<AG
# AGENTS.md — 故障排查工作台

> 故障排查模式工作区契约。本文件是 agent 行为唯一真源；sop/ 是经验与基线。

## 1. 开工
1. 先判故障域：本机 / 远程 / 环境差异（见 ts-fault-domain skill）；可多域但先主后次。
2. 按 ts-sop 做结构化 RCA；数据源未确认前不臆测。

## 2. 存放位置
| 内容 | 放哪 |
|---|---|
| 通用故障模式（换机器仍成立） | sop/通用故障模式/ |
| 本机专属经验（路径/版本/机器特征） | sop/本机经验/ |
| 各环境基线（组件/配置/网络/拓扑） | sop/环境基线/ |
| 单次故障处置记录 | incidents/<日期>-<摘要>/ |
| 正式故障报告 | reports/<日期>-<摘要>.md |

## 3. 纪律
- 结论分 事实/推断/建议；证据标注来源类型/查询条件/关键结果。
- 工具失败如实说明，不得当作"无异常数据"。
- 处置动作（重启/回滚/改配置）先说明影响面与回滚预案，经用户确认。
- 归档经验先问「换台机器还成立吗？」成立→通用，不成立→本机。
AG

cat > "$TARGET/sop/通用故障模式/README.md" <<G
# 通用故障模式

与环境、机器无关的可复用结论（换台机器仍成立）。命名：<类别>-<摘要>.md。
G
cat > "$TARGET/sop/本机经验/README.md" <<L
# 本机经验

带本机特征的教训（路径、版本、机器名）。命名：<日期>-<摘要>.md。
L
cat > "$TARGET/sop/环境基线/README.md" <<E
# 环境基线

各环境（dev/test/prod）的组件版本、配置要点、网络拓扑快照，用于环境差异对照。每个环境一份。
E

echo ""
echo "✅ 故障排查工作台初始化完成: $TARGET"
echo "  - workspace 指向该目录，DSH 选「故障排查模式」即可开始。"
echo "  - 先判故障域（本机/远程/环境），再按 SOP 做 RCA；经验按通用/本机分层归档。"
